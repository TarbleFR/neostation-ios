// Layout of the pinned arm64 donor, verified against EnsureInitializedLocked
// before this adapter is used. The caller holds the backend mutex and has
// joined AX. Never destroy the singleton or its mutex/vector: only the session.
inline void ReleaseDonorAudioSession(void* backend,
                                    void (*destroyStream)(void*),
                                    void (*quitSubsystem)(uint32_t)) {
  auto* bytes = static_cast<uint8_t*>(backend);
  void* stream = nullptr;
  std::memcpy(&stream, bytes + 0x40, sizeof(stream));
  const bool initialized = bytes[0x5c] != 0;
  if (stream) destroyStream(stream);
  stream = nullptr;
  std::memcpy(bytes + 0x40, &stream, sizeof(stream));
  if (initialized) quitSubsystem(0x10); // SDL_INIT_AUDIO
  std::memset(bytes + 0x54, 0, 9); // sample rate, channels, initialized
}


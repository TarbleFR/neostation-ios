  static String localeKey(Locale locale) {
    if (locale.languageCode == 'zh' &&
        (locale.scriptCode?.toLowerCase() == 'hant' ||
         ['TW', 'HK', 'MO'].contains(locale.countryCode?.toUpperCase()))) {
      return 'zh_Hant';
    }
    return locale.languageCode;
  }

  static Map<String, String> nativeUI(Locale locale) => {
    for (final key in [
      'nativeMenu', 'resumeGame', 'returnToLibrary', 'resumeHint', 'cancelReturn',
      'gameLanguage', 'gameLanguageHelp', 'languageEnglish', 'languageGerman',
      'languageFrench', 'languageSpanish', 'languageItalian', 'languageJapanese',
    ])
      key: forLocale(locale, key),
  };

  static String emptyLibraryText(BuildContext context) {
    return emptyLibrary[localeKey(Localizations.localeOf(context))] ??
        emptyLibrary['en']!;
  }

  static String localeKey(Locale locale) => locale.languageCode == 'zh' &&
          (locale.scriptCode?.toLowerCase() == 'hant' ||
              ['TW', 'HK', 'MO'].contains(locale.countryCode?.toUpperCase()))
      ? 'zh_Hant'
      : locale.languageCode;

  static String forLocale(Locale locale, String key, {int? count}) {
    final table = values[localeKey(locale)] ?? values['en']!;
    final value = table[key] ?? values['en']![key]!;
    return count == null ? value : value.replaceAll('{count}', '$count');
  }

  static String text(BuildContext context, String key, {int? count}) =>
      forLocale(Localizations.localeOf(context), key, count: count);

  static String launchError(Locale locale, String? errorCode) =>
      forLocale(locale, launchErrorKeys[errorCode] ?? 'launchFailed');

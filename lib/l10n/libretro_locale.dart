  /// Catalog key for a Flutter locale; script or region selects
  /// Traditional Chinese.
  static String localeKey(Locale locale) {
    final language = locale.languageCode;
    if (language == 'zh_Hant') return 'zh_Hant';
    if (language == 'zh') {
      final script = locale.scriptCode?.toLowerCase();
      final country = locale.countryCode?.toUpperCase();
      if (script == 'hant' || country == 'TW' || country == 'HK' || country == 'MO') {
        return 'zh_Hant';
      }
      return 'zh';
    }
    return values.containsKey(language) ? language : 'en';
  }

  static String forLocale(Locale locale, String key) =>
      values[localeKey(locale)]?[key] ?? values['en']![key] ?? key;

  static String format(Locale locale, String key, Map<String, Object?> arguments) {
    var text = forLocale(locale, key);
    for (final entry in arguments.entries) {
      text = text.replaceAll('{${entry.key}}', entry.value?.toString() ?? '');
    }
    return text;
  }

  static String text(BuildContext context, String key) =>
      forLocale(Localizations.maybeLocaleOf(context) ?? const Locale('en'), key);

  static String formatContext(
    BuildContext context,
    String key,
    Map<String, Object?> arguments,
  ) =>
      format(Localizations.maybeLocaleOf(context) ?? const Locale('en'), key, arguments);

  /// Labels sent to the native session.
  static Map<String, String> nativeUI(Locale locale) => <String, String>{
        for (final key in nativeKeys) key: forLocale(locale, key),
      };

  /// Translated message for a native error code; the raw technical detail
  /// travels separately.
  static String launchError(Locale locale, String? code) =>
      forLocale(locale, launchErrorKeys[code] ?? 'errorUnknown');

  /// libretro `retro_language` matching the NeoStation language, so cores
  /// that ship translations pick the same one.
  static int retroLanguage(Locale locale) {
    switch (localeKey(locale)) {
      case 'ja':
        return 1;
      case 'fr':
        return 2;
      case 'es':
        return 3;
      case 'de':
        return 4;
      case 'it':
        return 5;
      case 'pt':
        return 8;
      case 'ru':
        return 9;
      case 'ko':
        return 10;
      case 'zh_Hant':
        return 11;
      case 'zh':
        return 12;
      case 'id':
        return 24;
      default:
        return 0;
    }
  }

  /// Curated settings for the in-game menu, translated.
  static List<Map<String, Object>> coreSettings(Locale locale, LibretroCore core) =>
      <Map<String, Object>>[
        for (final setting in core.settings)
          <String, Object>{
            'key': setting.key,
            'label': forLocale(locale, setting.labelKey),
            'values': <Map<String, String>>[
              for (final value in setting.values)
                <String, String>{
                  'value': value,
                  'label': setting.valueLabelKeys.containsKey(value)
                      ? forLocale(locale, setting.valueLabelKeys[value]!)
                      : value,
                },
            ],
          },
      ];

  static String textForLocale(String localeKey, String key) =>
      (_values[localeKey] ?? _values['en']!)[key] ??
      _values['en']![key] ??
      key;

  static String text(BuildContext context, String key) {
    final locale = Localizations.localeOf(context);
    final localeKey = locale.languageCode == 'zh' &&
            locale.scriptCode?.toLowerCase() == 'hant'
        ? 'zh_Hant'
        : locale.languageCode;
    return textForLocale(localeKey, key);
  }

  static String launchBody(BuildContext context, String game) =>
      text(context, 'launchBody').replaceFirst('{game}', game);

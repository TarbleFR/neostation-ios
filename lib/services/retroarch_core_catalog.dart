  /// Importable game formats plus companion disc files and supported archives.
  /// These are file extensions, so cores' directory marker '/' is excluded.
  static Set<String> get recognizedGameExtensions => {
    for (final core in cores)
      for (final extension in core.validExtensions)
        if (extension != '/') extension.toLowerCase(),
    'zip',
    '7z',
    'cue',
    'm3u',
    'sub',
    'sbi',
  };

  static String normalizeSystem(String folder) => folder.trim().toLowerCase();
  static bool supportsSystem(String folder) =>
      supportedSystems.contains(normalizeSystem(folder));

  static List<RetroArchCoreDescriptor> coresForSystem(String folder) => cores
      .where((core) => core.systems.contains(normalizeSystem(folder)))
      .toList(growable: false);

  static RetroArchCoreDescriptor? findCore(String folder, String? identifier) {
    if (identifier == null || identifier.trim().isEmpty) return null;
    final requested = identifier.trim();
    for (final core in coresForSystem(folder)) {
      if (core.matchesIdentifier(requested)) return core;
    }
    return null;
  }

  static RetroArchCoreDescriptor defaultCore(String folder) {
    final available = coresForSystem(folder);
    if (available.isEmpty) throw ArgumentError.value(folder, 'folder');
    return available.first;
  }

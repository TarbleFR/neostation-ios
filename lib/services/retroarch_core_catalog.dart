/// Reviewed cores from the pinned RetroArch iOS donor IPA and supplements.
///
/// Each entry matches an App Store allowlisted, nonexperimental packaged
/// framework or a separately pinned supplemental build, plus an existing
/// NeoStation system definition. Unqualified hardware cores and missing
/// frameworks stay unavailable. PSP uses a separately pinned GLES build with
/// an interpreter profile because its framework is absent from the donor IPA.
/// N64 uses the donor GLES3 core with protected interpreter and GLideN64 options.
class RetroArchCoreDescriptor {
  const RetroArchCoreDescriptor({
    required this.identifier,
    required this.displayName,
    required this.frameworkStem,
    required this.systems,
    required this.validExtensions,
  });

  final String identifier;
  final String displayName;
  final String frameworkStem;
  final Set<String> systems;

  /// Exact supported_extensions from the pinned donor core information.
  final Set<String> validExtensions;
  String get uniqueId => 'ios_retroarch_internal:$identifier';
  String get frameworkName => '$frameworkStem.libretro.framework';
  String get executableName => '$frameworkStem.libretro';

  bool matchesIdentifier(String value) =>
      value == identifier ||
      value == uniqueId ||
      value == executableName ||
      value == frameworkName ||
      value == '${identifier}_libretro' ||
      value == '${identifier}_libretro.so' ||
      value == '${identifier}_libretro.dll' ||
      value == '${identifier}_libretro.dylib';
}


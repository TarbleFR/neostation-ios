def replace_once(path: Path, old: str, new: str, description: str) -> None:
    text = path.read_text(encoding="utf-8")
    count = text.count(old)
    if count == 0 and new in text:
        return
    if count != 1:
        raise SystemExit(f"{description}: expected exactly one anchor in {path}, got {count}")
    path.write_text(text.replace(old, new, 1), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("dolphin_root", type=Path)
    args = parser.parse_args()
    root = args.dolphin_root.resolve()

    cmake = root / "Source/iOS/Library/CMakeLists.txt"
    memory = root / "Source/Core/Common/MemoryUtil_iOS_LuckTXM.cpp"
    bridge = root / "Source/iOS/Library/NeoStationBridge.mm"
    if not cmake.is_file() or not memory.is_file():
        raise SystemExit("Not a compatible OatmealDome/dolphin-ios checkout")

    replace_once(
        cmake,
        "  HostQueue.mm\n)",
        "  HostQueue.mm\n  NeoStationBridge.mm\n)",
        "add NeoStation bridge source",
    )
    definition = "target_compile_definitions(dolphin PRIVATE NEOSTATION_INTERNAL_DOLPHIN=1)"
    cmake_text = cmake.read_text(encoding="utf-8")
    if definition not in cmake_text:
        cmake_text += f"\n# NeoStation process-local bridge\n{definition}\n"
        cmake.write_text(cmake_text, encoding="utf-8")

    replace_once(
        memory,
        "  if (!rx_ptr)\n",
        "  if (rx_ptr == MAP_FAILED)\n",
        "correct mmap failure detection",
    )

    bridge.write_text(BRIDGE_SOURCE, encoding="utf-8")

    updated = memory.read_text(encoding="utf-8")
    required = (
        'brk #0x69',
        '"mov x0, %0\\n"',
        '"mov x1, %1\\n"',
        'if (rx_ptr == MAP_FAILED)',
    )
    missing = [needle for needle in required if needle not in updated]
    if missing:
        raise SystemExit("Legacy Dolphin ABI check failed: " + ", ".join(missing))
    if "JIT26PrepareRegion" in updated or "brk #0xf00d" in updated:
        raise SystemExit("Universal JIT ABI leaked into the Dolphin legacy allocator")

    print("Patched Dolphin for isolated NeoStation JITARM64/Metal embedding.")


if __name__ == "__main__":
    main()

"""Patch OatmealDome/dolphin-ios into a strict NeoStation-owned dylib.

The generated ABI is deliberately tiny and process-local. It accepts only
GameCube/Wii images, requires the existing Dolphin BRK #0x69 allocator protocol,
requires JITARM64 and Metal, and exposes deterministic cleanup hooks.
"""


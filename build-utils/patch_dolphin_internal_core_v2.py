def replace_once(path: Path, old: str, new: str, description: str) -> None:
    text = path.read_text(encoding='utf-8')
    count = text.count(old)
    if count == 0 and new in text:
        return
    if count != 1:
        raise SystemExit(f'{description}: expected one anchor in {path}, got {count}')
    path.write_text(text.replace(old, new, 1), encoding='utf-8')


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument('dolphin_root', type=Path)
    root = parser.parse_args().dolphin_root.resolve()
    cmake = root / 'Source/iOS/Library/CMakeLists.txt'
    memory = root / 'Source/Core/Common/MemoryUtil_iOS_LuckTXM.cpp'
    bridge = root / 'Source/iOS/Library/NeoStationBridge.mm'
    if not cmake.is_file() or not memory.is_file():
        raise SystemExit('Not a compatible pinned dolphin-ios checkout')
    replace_once(cmake, '  HostQueue.mm\n)', '  HostQueue.mm\n  NeoStationBridge.mm\n)', 'add NeoStation bridge')
    definition = 'target_compile_definitions(dolphin PRIVATE NEOSTATION_INTERNAL_DOLPHIN=1)'
    text = cmake.read_text()
    if definition not in text:
        cmake.write_text(text + '\n' + definition + '\n')
    replace_once(memory, '  if (!rx_ptr)\n', '  if (rx_ptr == MAP_FAILED)\n', 'mmap failure detection')
    bridge.write_text(BRIDGE_SOURCE, encoding='utf-8')
    updated = memory.read_text()
    required = ('brk #0x69', '"mov x0, %0\\n"', '"mov x1, %1\\n"', 'if (rx_ptr == MAP_FAILED)')
    if any(needle not in updated for needle in required):
        raise SystemExit('Pinned legacy allocator protocol changed')

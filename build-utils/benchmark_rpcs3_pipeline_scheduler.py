#!/usr/bin/env python3
"""Deterministic queueing benchmark for the Build 258 pipeline dispatcher.

This isolates scheduler head-of-line blocking. It is not a substitute for the
real-device FPS comparison generated by compare_rpcs3_core_profiles.py.
"""

from __future__ import annotations

from dataclasses import dataclass, field
import statistics


@dataclass
class Worker:
    completions: list[float] = field(default_factory=list)

    def retire(self, now: float) -> None:
        self.completions = [value for value in self.completions if value > now]

    @property
    def pending(self) -> int:
        return len(self.completions)

    @property
    def available(self) -> float:
        return self.completions[-1] if self.completions else 0.0

    def enqueue(self, arrival: float, duration: float) -> float:
        started = max(arrival, self.available)
        self.completions.append(started + duration)
        return started - arrival


def simulate(jobs: list[tuple[float, float]], worker_count: int, least_loaded: bool) -> dict[str, float]:
    workers = [Worker() for _ in range(worker_count)]
    waits: list[float] = []
    cursor = 0
    final_completion = 0.0
    for arrival, duration in jobs:
        for worker in workers:
            worker.retire(arrival)
        start = cursor % worker_count
        cursor += 1
        selected = start
        if least_loaded:
            best_load = workers[selected].pending
            for offset in range(1, worker_count):
                candidate = (start + offset) % worker_count
                if workers[candidate].pending < best_load:
                    selected = candidate
                    best_load = workers[candidate].pending
                    if best_load == 0:
                        break
        waits.append(workers[selected].enqueue(arrival, duration))
        final_completion = max(final_completion, workers[selected].available)
    ordered = sorted(waits)
    p95 = ordered[min(len(ordered) - 1, int(len(ordered) * 0.95))]
    return {
        "mean_queue_ms": statistics.fmean(waits),
        "p95_queue_ms": p95,
        "maximum_queue_ms": max(waits),
        "makespan_ms": final_completion,
    }


def benchmark() -> tuple[dict[str, float], dict[str, float]]:
    # One expensive driver pipeline starts on worker 0. Short pipelines then
    # arrive while it is still compiling. Blind RR repeatedly queues behind it.
    jobs = [(0.0, 120.0), (0.0, 5.0)]
    jobs.extend((float(at), 5.0) for at in range(10, 121, 10))
    return simulate(jobs, 2, False), simulate(jobs, 2, True)


def main() -> None:
    before, after = benchmark()
    print("pipeline scheduler microbenchmark (2 workers, milliseconds)")
    print("metric                 round-robin  least-loaded  delta")
    for key in ("mean_queue_ms", "p95_queue_ms", "maximum_queue_ms", "makespan_ms"):
        print(f"{key:22} {before[key]:11.3f} {after[key]:13.3f} {after[key] - before[key]:8.3f}")


if __name__ == "__main__":
    main()
